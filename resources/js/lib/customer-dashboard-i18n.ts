export type DashboardWord=keyof typeof words;

export function useDashboardText(){
 const {locale}=usePage<SharedData>().props;
 const index=locale==='my'?1:locale==='th'?2:0;
 const language=locale==='my'?'my-MM':locale==='th'?'th-TH':'en-US';
 const t=(key:DashboardWord,values:Record<string,string|number>={})=>words[key][index].replace(/\{(\w+)\}/g,(_,name:string)=>String(values[name]??''));
 const number=(value:number,digits=0)=>new Intl.NumberFormat(language,{maximumFractionDigits:digits}).format(value);
 /** Source seconds as whole minutes, the unit customers are billed in. */
 const minutes=(seconds:number)=>number(Math.round(seconds/60))+' '+t('minutesShort');
 return {t,number,minutes,locale,language};
}
