/** A word in a specific locale, used right after the interface language changes. */
export function preferenceWord(key:PreferenceWord,locale:string){return words[key][locale==='my'?1:locale==='th'?2:0];}

export function usePreferenceText(){
 const {locale}=usePage<SharedData>().props;
 const index=locale==='my'?1:locale==='th'?2:0;
 const language=locale==='my'?'my-MM':locale==='th'?'th-TH':'en';
 return {t:(key:PreferenceWord)=>words[key][index],locale,language};
}
